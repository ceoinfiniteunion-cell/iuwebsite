if (!args.includes('--no-capture')) await capture(PAGES.map(p => p.key).filter(k => !only.length || only.includes(k)));

// ---------------------------------------------------------------- CSS from inline styles
const TOKENS = [
  ['rgb(10, 7, 6)', 'var(--bg-0)'], ['rgb(14, 9, 9)', 'var(--bg-1)'], ['rgb(18, 13, 13)', 'var(--bg-2)'],
  ['rgb(7, 5, 4)', 'var(--bg-deep)'], ['rgb(12, 8, 8)', 'var(--card)'], ['rgb(237, 232, 229)', 'var(--fg)'],
  ['rgb(201, 192, 188)', 'var(--fg-2)'], ['rgb(179, 169, 169)', 'var(--muted)'], ['rgb(168, 158, 158)', 'var(--muted-2)'],
  ['rgb(138, 128, 128)', 'var(--muted-3)'], ['rgb(212, 0, 0)', 'var(--red)'], ['rgb(255, 59, 47)', 'var(--red-hot)'],
  ['rgb(255, 42, 31)', 'var(--red-text)'],
];
function cssBody(st) {
  let s = st.trim();
  for (const [a, b] of TOKENS) s = s.split(a).join(b);
  s = s.replace(/"Space Grotesk", sans-serif/g, '"Space Grotesk", "SG Fallback", sans-serif');
  // vendor prefixes the browser's normalised cssText dropped
  s = s.replace(/(^|;\s*)backdrop-filter:\s*([^;]+)/g, '$1-webkit-backdrop-filter: $2; backdrop-filter: $2');
  s = s.replace(/(^|;\s*)user-select:\s*([^;]+)/g, '$1-webkit-user-select: $2; user-select: $2');
  s = s.replace(/(^|;\s*)background-clip:\s*text/g, '$1-webkit-background-clip: text; background-clip: text');
  // iOS: dynamic toolbar — 100vh sticky scenes use the small viewport when supported
  s = s.replace(/(^|;\s*)(min-height|height):\s*100vh(?=;|$)/g, '$1$2: 100vh; $2: 100svh');
  return s.replace(/;\s*$/, '').replace(/;\s+/g, ';').replace(/:\s+/g, ':');
}

const data = new Map();
for (const p of PAGES) {
  const f = path.join(CACHE, p.key + '.json');
  if (!fs.existsSync(f)) throw new Error(`no capture for ${p.key} — run without --no-capture`);
  data.set(p.key, JSON.parse(fs.readFileSync(f, 'utf8')));
}
const styleCls = new Map(); // css body → class
const hoverCls = new Map(); // pseudo|body → class
const name36 = (pre, n) => pre + n.toString(36);
for (const p of PAGES) {
  const d = data.get(p.key);
  for (const st of d.styles) { const b = cssBody(st); if (!styleCls.has(b)) styleCls.set(b, name36('s', styleCls.size)); }
  for (const h of Object.values(d.hov)) { const k = h.pseudo + '|' + cssBody(h.body); if (!hoverCls.has(k)) hoverCls.set(k, name36('h', hoverCls.size)); }
}

// ---------------------------------------------------------------- shared assets
const read = f => fs.readFileSync(f, 'utf8');
fs.mkdirSync('assets/css', { recursive: true });
fs.mkdirSync('assets/js', { recursive: true });
const clean = dir => { for (const f of fs.readdirSync(dir)) if (/\.[0-9a-f]{10}\.(css|js)$/.test(f)) fs.rmSync(path.join(dir, f)); };
clean('assets/css'); clean('assets/js');

const hoverCss = [...hoverCls].map(([k, c]) => { const [pseudo, body] = k.split(/\|(.*)/s); return `.${c}:${pseudo}{${body}}`; }).join('\n');
const siteCss = `/* Infinite Union — interaction layer (hover / focus). Generated by scripts/render-design.mjs */\n${hoverCss}\n`;
const siteCssName = `site.${hash(siteCss)}.css`;
fs.writeFileSync(path.join('assets/css', siteCssName), siteCss);

// 3D bundle: design modules + three r185 + Draco, copied into a content-hashed directory
const files3d = ['iu-snake.js', 'iu-glyph.js'];
const src3d = f => fs.existsSync(path.join('src/3d', f)) ? path.join('src/3d', f) : path.join(DESIGN, f);
const h3d = hash(files3d.map(f => read(src3d(f))).join('') + read(path.join(DESIGN, 'vendor/three.module.min.js')));
const dir3d = `assets/3d/${h3d}`;
if (!fs.existsSync(dir3d)) {
  for (const d of fs.existsSync('assets/3d') ? fs.readdirSync('assets/3d') : []) if (/^[0-9a-f]{10}$/.test(d)) fs.rmSync(path.join('assets/3d', d), { recursive: true });
  fs.mkdirSync(dir3d, { recursive: true });
  for (const f of files3d) {
    const out = await minify(read(src3d(f)), { module: true, compress: true, mangle: true });
    fs.writeFileSync(path.join(dir3d, f), out.code + '\n');
  }
  fs.cpSync(path.join(DESIGN, 'vendor'), path.join(dir3d, 'vendor'), { recursive: true });
  fs.cpSync(path.join(DESIGN, 'utils'), path.join(dir3d, 'utils'), { recursive: true });
  fs.rmSync(path.join(dir3d, 'vendor/draco/draco_decoder.js')); // WASM decoder is used; the asm.js fallback is 500 KB
}
// GLB stays on Cloudinary (3.8 MB > the repo's 800 KB pre-commit limit); <link rel=preconnect> is emitted on pages with 3D
const glb = 'https://res.cloudinary.com/etdq5y69/raw/upload/v1783282631/snake3d.glb';

// motion.js (all page animations + forms) — hashed, minified
let motionSrc = read('src/js/motion.js').replace('__3D_BASE__', `/${dir3d}/`).replace('__GLB__', glb);
const motion = (await minify(motionSrc, { module: true, compress: { passes: 2 }, mangle: true })).code + '\n';
const motionName = `motion.${hash(motion)}.js`;
