const fontsCss = read('src/css/fonts.css');
const baseCss = read('src/css/base.css');
const minCss = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s*\n\s*/g, '').replace(/\s*([{};,>])\s*/g, '$1').replace(/;}/g, '}');

// ---------------------------------------------------------------- portfolio images
const SHOT = {
  'transferkharkiv.com.ua': ['transferkharkiv', 1440, 990], 'parrotschool.com.ua': ['parrotschool', 1440, 990],
  'studentik.com.ua': ['studentik', 1440, 990], 'respectcar.com.ua': ['respectcar', 1440, 990],
  'labrobiocore.com.ua': ['labrobiocore', 1440, 990], 'gym4fit': ['gym4fit', 1440, 765], 'truebar.com.ua/og': ['truebar', 1440, 990],
  '7795-guests-table': ['truebar-black', 1080, 720, true], '1371-lounge-interior': ['truebar-white', 1080, 1620, true],
};
function picture(img, slug, w, h, single) {
  const alt = img.getAttribute('alt') || '';
  const cls = img.getAttribute('class');
  const b = `/assets/img/portfolio/${slug}`;
  const ss = ext => single ? `${b}.${ext}` : `${b}-720.${ext} 720w, ${b}.${ext} ${w}w`;
  const sizes = single ? '' : ' sizes="(max-width: 819px) 92vw, 44vw"';
  return `<picture><source type="image/avif" srcset="${ss('avif')}"${sizes}><source type="image/webp" srcset="${ss('webp')}"${sizes}>` +
    `<img src="${b}.webp" alt="${esc(alt)}" width="${w}" height="${h}" loading="lazy" decoding="async"${cls ? ` class="${cls}"` : ''}></picture>`;
}

// ---------------------------------------------------------------- per-page assembly
const T = {
  uk: { skip: 'До контенту', consent: 'Надсилаючи заявку, ви погоджуєтесь з', policy: 'політикою конфіденційності', privacy: 'Політика конфіденційності', site: 'Сайт' },
  en: { skip: 'Skip to content', consent: 'By sending the request you agree to our', policy: 'privacy policy', privacy: 'Privacy policy', site: 'Website' },
};
const hrefOf = h => {
  if (/^IU Home v2\.dc\.html/.test(h)) return '/' + h.slice('IU Home v2.dc.html'.length);
  if (/^IU 404\.dc\.html/.test(h)) return '/404.html';
  const m = h.match(/^IU Page\.dc\.html\?p=([^#&]+)(#.*)?$/);
  if (m) return pathOfKey(decodeURIComponent(m[1])) + (m[2] || '');
  return h;
};
const report = [];

for (const p of PAGES) {
  if (only.length && !only.includes(p.key)) continue;
  const d = data.get(p.key);
  const t = T[p.lang] || T.uk;
  const used = new Set();
  let html = d.html
    .replace(/class="([^"]+)"/g, (m, c) => `class="${c.split(' ').map(x => {
      if (x.startsWith('__S')) { const cl = styleCls.get(cssBody(d.styles[+x.slice(3)])); used.add(cl); return cl; }
      if (x.startsWith('__H')) { const h = d.hov[x.slice(3)]; return hoverCls.get(h.pseudo + '|' + cssBody(h.body)); }
      return x;
    }).join(' ')}"`)
    .replace(/href="([^"]*)"/g, (m, h) => `href="${hrefOf(h.replace(/&amp;/g, '&')).replace(/&/g, '&amp;')}"`);

  const root = parse(html, { comment: false, blockTextElements: { script: true, style: true } });
  const $ = s => root.querySelector(s), $$ = s => root.querySelectorAll(s);

  // prototype-only link to the 404 page in the footer (would put a soft-404 link on every page)
  for (const a of $$('a[href="/404.html"]')) if (!$('main') || !a.closest('main')) a.remove();
  // images
  for (const img of $$('img')) {
    const src = img.getAttribute('src') || '';
    const shot = Object.entries(SHOT).find(([k]) => src.includes(encodeURIComponent(k)) || src.includes(k));
    if (shot) { const [slug, w, h, single] = shot[1]; img.replaceWith(picture(img, slug, w, h, single)); continue; }
    if (/iu-logo\.png$/.test(src)) {
      const size = p.key === 'home' ? 32 : 30;
      img.setAttribute('src', '/assets/img/iu-logo.png'); img.setAttribute('width', String(size)); img.setAttribute('height', String(size));
      img.setAttribute('decoding', 'async');
      continue;
    }
    if (/avatar\.jpe?g$/.test(src)) {
      const cls = img.getAttribute('class');
      img.replaceWith(`<picture><source type="image/avif" srcset="/assets/img/avatar.avif"><source type="image/webp" srcset="/assets/img/avatar.webp"><img src="/assets/img/avatar.jpg" alt="${esc(img.getAttribute('alt') || '')}" width="656" height="711" loading="lazy" decoding="async"${cls ? ` class="${cls}"` : ''}></picture>`);
      continue;
    }
    report.push(`${p.key}: unmapped image ${src.slice(0, 80)}`);
  }
  for (const fb of $$('[data-shot-fallback]')) fb.remove();
  for (const el of $$('[data-shot]')) el.removeAttribute('data-shot');

  // lead forms: honeypot, autocomplete, consent line, a11y of the success message
  for (const form of $$('form[data-lead]')) {
    form.setAttribute('novalidate', '');
    form.setAttribute('aria-label', p.lang === 'en' ? 'Project request' : 'Заявка на проєкт');
    const ac = { cn: 'name', cphone: 'tel', cc: 'off' };
    for (const [n, v] of Object.entries(ac)) form.querySelector(`[name="${n}"]`)?.setAttribute('autocomplete', v);
    form.querySelector('[name="cphone"]')?.setAttribute('inputmode', 'tel');
    const sent = form.querySelector('[data-sent]');
    if (sent) { sent.setAttribute('hidden', ''); sent.setAttribute('aria-live', 'polite'); }
    const hp = '<label class="iu-hp" aria-hidden="true">Website<input name="website" type="text" tabindex="-1" autocomplete="off"></label>';
    const consent = `<p class="iu-consent">${t.consent} <a href="/services/privacy/">${t.policy}</a>.</p>`;
    if (sent) sent.insertAdjacentHTML('beforebegin', hp + consent); else form.insertAdjacentHTML('beforeend', hp + consent);
  }
  // footer: privacy link on every page
  const foot = $('footer');
  if (foot && !foot.querySelector('a[href="/services/privacy/"]')) {
    const navs = foot.querySelectorAll('nav');
    const last = navs[navs.length - 1];
    const ref = last && last.querySelectorAll('a')[0];
    if (ref) last.insertAdjacentHTML('beforeend', `<a href="/services/privacy/" class="${ref.getAttribute('class') || ''}">${t.privacy}</a>`);
    else foot.insertAdjacentHTML('beforeend', `<a href="/services/privacy/">${t.privacy}</a>`);
  }
  const vn = $('#veil-name');
  if (vn) vn.set_content(esc(p.name || '∞'));
  const main = $('main');
  if (main) main.setAttribute('id', 'main'); else report.push(`${p.key}: no <main>`);
  for (const a of $$('a[target="_blank"]')) a.setAttribute('rel', 'noopener noreferrer');
  for (const i of $$('input:not([type])')) i.setAttribute('type', 'text');
  for (const b of $$('button:not([type])')) b.setAttribute('type', 'button');
  for (const a of $$('a[href^="tel:"]')) if (/\d/.test(a.text) && a.text.length < 40) a.set_content(a.innerHTML.replace(/(\S) (?=\S)/g, "$1&nbsp;"));
  // 3D canvases get an accessible fallback name; decorative
  for (const c of $$('canvas')) c.setAttribute('aria-hidden', 'true');

  // FAQ (visible <details>) → FAQPage JSON-LD
  const faq = $$('main details').map(dt => {
    const sum = dt.querySelector('summary');
    const q = (sum?.querySelector('h3')?.text || sum?.text || '').replace(/\s+/g, ' ').replace(/\s*[+×]\s*$/, '').trim();
    const a = dt.childNodes.filter(n => n !== sum).map(n => n.text).join(' ').replace(/\s+/g, ' ').trim();
    return { q, a };
  }).filter(f => f.q && f.a);
  const items = p.type === 'portfolio' ? $$('#projects article').map(a => ({ name: a.querySelector('h2')?.text.trim(), url: a.querySelector('a[target="_blank"]')?.getAttribute('href') })).filter(i => i.name) : [];

  // CSS: tokens + fonts + prototype base + additions + this page's classes
  const pageCss = [...styleCls].filter(([, c]) => used.has(c)).map(([b, c]) => `.${c}{${b}}`).join('');
  const protoBase = d.base.replace(/'Space Grotesk',sans-serif/g, "'Space Grotesk','SG Fallback',sans-serif");
  const critical = minCss(fontsCss) + minCss(protoBase) + minCss(baseCss) + pageCss;

  const out = root.toString();
  const scripts = [GTM, GTAG, BOOT];
  const lang = p.lang || 'uk';
  const preFonts = ['/assets/fonts/sg-latin.woff2', lang === 'en' ? '/assets/fonts/jbm-latin.woff2' : '/assets/fonts/jbm-cyrillic.woff2'];
  const page = `<!DOCTYPE html>
<html lang="${lang}">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta http-equiv="Content-Security-Policy" content="${csp(scripts.map(sha256))}">
<meta name="referrer" content="strict-origin-when-cross-origin">
${seoHead(p, { faq, items })}
<script>${BOOT}</script>
${preFonts.map(f => `<link rel="preload" href="${f}" as="font" type="font/woff2" crossorigin>`).join('\n')}
<link rel="preload" href="/assets/css/${siteCssName}" as="style" data-iu-css>
<noscript><link rel="stylesheet" href="/assets/css/${siteCssName}"></noscript>
${p.key === 'home' || p.key === '404' ? '<link rel="preconnect" href="https://res.cloudinary.com" crossorigin>\n' : ''}<style>${critical}</style>
<script>${GTM}</script>
<script>${GTAG}</script>
</head>
<body>
<noscript><iframe src="https://www.googletagmanager.com/ns.html?id=GTM-WXZW3NHF" height="0" width="0" style="display:none;visibility:hidden" title="Google Tag Manager"></iframe></noscript>
<a class="iu-skip" href="#main">${t.skip}</a>
${out.trim()}
<script type="module" src="/assets/js/${motionName}"></script>
</body>
</html>
`;
  const file = p.key === '404' ? '404.html' : fileOf(p.path);
  fs.mkdirSync(path.dirname(file) || '.', { recursive: true });
  fs.writeFileSync(file, page.replace(/[ \t]+$/gm, ''));
  const kb = (Buffer.byteLength(page) / 1024).toFixed(0);
  console.log(`wrote ${file} (${kb} KB, ${used.size} classes, faq ${faq.length}${items.length ? ', items ' + items.length : ''})`);
}
